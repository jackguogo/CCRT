/* 生成「正确 N 个」型分档 */
const cnt = (max, unit = "个") =>
  Array.from({ length: max + 1 }, (_, i) => [max - i, max - i === 0 ? `0 ${unit}` : `正确 ${max - i} ${unit}`]);
/* 生成「错误 N 个」型分档（ADAS 类按错误计分） */
