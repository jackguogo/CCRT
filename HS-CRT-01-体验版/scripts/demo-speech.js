// 取某题的口述文本；无映射时用各空标签兜底
function speechOf(code, itemId, item) {
  const sp = SPEECH[code + ":" + itemId];
  if (sp) return sp.filter(Boolean).join("、");
  const labels = ((item && item.parts) || []).map((p) => p.l).filter(Boolean);
  return labels.length ? labels.join("、") : "已口头作答";
}

